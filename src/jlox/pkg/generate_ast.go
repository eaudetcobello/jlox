package jlox

import (
	"fmt"
	"go/format"
	"os"
	"strings"
)

// Parses a string in the format:
// Binary : left Expr, operator Token, right Expr
// Into a valid go struct definition.
func defineType(builder *strings.Builder, structName string, fields string) error {
	var tempBuilder strings.Builder

	// use a tempbuilder so that we don't write to the real builder
	// until we know no error has occurred
	fmt.Fprintf(&tempBuilder, "type %s struct {\n", structName)

	for _, field := range strings.Split(fields, ",") {
		parts := strings.Fields(field)

		if len(parts) == 2 {
			name, fieldType := parts[0], parts[1]
			fmt.Fprintf(&tempBuilder, "  %s %s\n", name, fieldType)

			continue
		}

		return fmt.Errorf("field %v should have exactly two parts: field name and field name", parts)
	}

	fmt.Fprint(&tempBuilder, "}\n\n")

	fmt.Fprintf(&tempBuilder, "func (%s) expr() {}\n", structName)

	builder.WriteString(tempBuilder.String())

	return nil
}

func GenerateAst(outputFile string, types []string) error {
	var builder strings.Builder

	builder.WriteString("// Code generated by \"jlox generate-ast\". DO NOT EDIT.\n\n")

	builder.WriteString("package jlox\n\n")

	builder.WriteString("type Expr interface { expr() } \n\n")

	for _, t := range types {
		structName := strings.ReplaceAll(strings.Split(t, ":")[0], " ", "")
		fields := strings.Split(t, ":")[1]

		if err := defineType(&builder, structName, fields); err != nil {
			return err
		}
	}

	src, err := format.Source([]byte(builder.String()))
	if err != nil {
		return err
	}

	if outputFile != "" {
		err := os.WriteFile(outputFile, src, 0o644)
		if err != nil {
			return err
		}

		return nil
	}

	fmt.Print(string(src))

	return nil
}
